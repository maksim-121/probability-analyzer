"""
Прототип: начнётся ли совещание вовремя? (Монте-Карло, движок из Snow Boom)

Совещание в 14:00, «вовремя» = задержка старта не больше 5 минут.
Совещание начинается, когда готово ВСЁ: пришёл Иван, пришла Мария, освободилась переговорка.
"""
import numpy as np

N = 1_000_000          # число прогонов (как число спинов)
SEED = 20261117        # сид — как в Snow Boom: один сид = один и тот же результат
GRACE = 5              # допустимая задержка, мин

rng = np.random.default_rng(SEED)

def table(values, weights, n):
    """Дискретное распределение «значение — вес». Это ровно лента барабана:
    вес символа на ленте = вес значения в таблице."""
    w = np.array(weights, float)
    return np.array(values)[rng.choice(len(values), size=n, p=w / w.sum())]

# 1) Иван едет на автобусе: опоздание транспорта, мин
ivan = table([0, 5, 10, 20], [50, 30, 15, 5], N)

# 2) Мария на обеде до 13:50; обед затягивается на 0/10/20 мин.
#    У неё 10 минут запаса, поэтому опоздание = задержка обеда − 10 (не меньше 0)
lunch = table([0, 10, 20], [60, 30, 10], N)
maria = np.maximum(lunch - 10, 0)

# 3) Переговорка: прошлое совещание затягивается в 25% случаев, на 5–15 мин (равномерно)
overrun = rng.random(N) < 0.25
room = np.where(overrun, rng.uniform(5, 15, N), 0.0)

# Итог: старт = когда готов последний -> максимум
delay = np.maximum.reduce([ivan, maria, room])
on_time = delay <= GRACE

p = on_time.mean()
se = np.sqrt(p * (1 - p) / N)           # та же формула погрешности, что у hit rate
exact = (0.50 + 0.30) * (0.60 + 0.30) * 0.75   # И -> умножаем (события независимы)

print(f"P(вовремя)  MC   = {p:.4%}  ± {1.96*se:.3%} (95%)")
print(f"P(вовремя) точно = {exact:.4%}")
print(f"Средняя задержка = {delay.mean():.2f} мин")
print(f"Медиана / P90    = {np.median(delay):.1f} / {np.percentile(delay, 90):.1f} мин")
print("Кто чаще всего виноват в срыве (при опоздании):")
late = ~on_time
for name, x in [("Иван", ivan), ("Мария", maria), ("Переговорка", room)]:
    print(f"  {name:12s} {((x == delay) & (x > GRACE))[late].mean():.1%}")
